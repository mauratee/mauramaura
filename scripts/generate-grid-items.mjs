import { readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const IMAGES_DIR = path.join(__dirname, "..", "public", "images");
const OUTPUT_FILE = path.join(__dirname, "..", "src", "app", "(public)", "gridItems.generated.ts");

const IMAGE_EXTENSIONS = new Set([".jpg", ".jpeg", ".png", ".webp", ".gif"]);

// Files in public/images that aren't gallery photos (screenshots, etc).
const EXCLUDE = new Set(["Screenshot_2026-01-24.png"]);

const filenames = readdirSync(IMAGES_DIR)
  .filter((name) => IMAGE_EXTENSIONS.has(path.extname(name).toLowerCase()))
  .filter((name) => !EXCLUDE.has(name))
  .sort((a, b) => a.localeCompare(b));

const items = filenames.map((filename, index) => {
  const id = index + 1;
  const category = id % 2 === 0 ? "shop" : "work";
  return {
    id,
    title: null,
    price: null,
    href: `/${category}/item-${id}`,
    image: `/images/${filename}`,
  };
});

const header = `// AUTO-GENERATED by scripts/generate-grid-items.mjs — do not edit by hand.
// Regenerated automatically on \`npm run dev\` / \`npm run build\`.
// To exclude a file from the grid, add it to the EXCLUDE set in that script.

export type GridItem = {
  id: number;
  title: string | null;
  price: string | null;
  href: string;
  image: string;
};
`;

const body = `export const gridItems: GridItem[] = ${JSON.stringify(items, null, 2)};\n`;

writeFileSync(OUTPUT_FILE, header + "\n" + body);
console.log(`Generated ${items.length} grid items -> ${path.relative(process.cwd(), OUTPUT_FILE)}`);
